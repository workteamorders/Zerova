// Encodes the 36 glyph skeletons for the on-chain renderer.
// Format per glyph: [strokeCount] then per stroke [pointCount, x0,y0, x1,y1, ...], units of 1/100 glyph height (y may reach 104).
const GL=require('./glyphs_src.js');
const chars='ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';
let bytes=[],offs=[],widths=[];
for(const c of chars){const g=GL[c];offs.push(bytes.length);widths.push(Math.round(g.w*100));
  bytes.push(g.s.length);
  for(const st of g.s){ // drop near-duplicate points
    const pts=[];for(const p of st){const q=[Math.round(p[0]*100)+10,Math.round(p[1]*100)+10];const l=pts[pts.length-1];if(!l||l[0]!==q[0]||l[1]!==q[1])pts.push(q)}
    if(pts.length>255)throw new Error('too many points');bytes.push(pts.length);
    for(const q of pts){if(q[0]<0||q[0]>255||q[1]<0||q[1]>255)throw new Error(c+' out of range '+q);bytes.push(q[0],q[1])}}}
const hex=Buffer.from(bytes).toString('hex');
const offHex=offs.map(o=>o.toString(16).padStart(4,'0')).join('');
const wHex=Buffer.from(widths).toString('hex');
require('fs').writeFileSync(require('path').join(__dirname,'../src/ZerovaGlyphs.sol'),`// SPDX-License-Identifier: MIT
pragma solidity 0.8.26;

/// @notice Skeletons of A-Z and 0-9 used by the renderer. Generated by scripts/gen-glyphs.js from the web engine.
/// Per glyph: [strokeCount] then per stroke [pointCount, x0, y0, x1, y1, ...] in 1/100 of the glyph height, plus 10.
library ZerovaGlyphs {
    bytes internal constant DATA = hex"${hex}";
    /// @dev uint16 big-endian offsets into DATA, in the order A-Z then 0-9.
    bytes internal constant OFFSETS = hex"${offHex}";
    /// @dev advance width of each glyph in 1/100 of the glyph height.
    bytes internal constant WIDTHS = hex"${wHex}";

    /// @return index of the glyph for an uppercase letter or digit
    function indexOf(bytes1 c) internal pure returns (uint256) {
        uint8 v = uint8(c);
        if (v >= 65 && v <= 90) return v - 65;
        if (v >= 48 && v <= 57) return 26 + v - 48;
        revert("glyph");
    }

    function offset(uint256 i) internal pure returns (uint256) {
        return (uint256(uint8(OFFSETS[2 * i])) << 8) | uint256(uint8(OFFSETS[2 * i + 1]));
    }

    function width(uint256 i) internal pure returns (uint256) {
        return uint8(WIDTHS[i]);
    }
}
`);
console.log('bytes',bytes.length,'max points', 'ok');
